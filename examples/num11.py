"""Задача 11. Если слово 'abb', то заменить его на 'a', иначе на 'b'."""

ALPHABET = {"a", "b"}

TRANSITIONS = {
    # q0, q1, q2, q3: проверяем, что слово ровно 'abb'
    ("q0", "a"): ("a", "R", "q1"),
    ("q0", "b"): ("b", "R", "q_err_r"),
    ("q0", "λ"): ("b", "N", "STOP"),     # Пустое слово — сразу 'b'

    ("q1", "b"): ("b", "R", "q2"),
    ("q1", "a"): ("a", "R", "q_err_r"),
    ("q1", "λ"): ("λ", "R", "q_err_r"),

    ("q2", "b"): ("b", "R", "q3"),
    ("q2", "a"): ("a", "R", "q_err_r"),
    ("q2", "λ"): ("λ", "R", "q_err_r"),

    ("q3", "λ"): ("λ", "L", "q_succ_l"),
    ("q3", "a"): ("a", "R", "q_err_r"),
    ("q3", "b"): ("b", "R", "q_err_r"),

    # ВЕТКА ОШИБКИ (слово не равно 'abb')
    # Сначала стираем всё вправо до конца
    ("q_err_r", "a"): ("λ", "R", "q_err_r"),
    ("q_err_r", "b"): ("λ", "R", "q_err_r"),
    ("q_err_r", "λ"): ("λ", "L", "q_err_l"),

    # Двигаемся влево через пустые символы, пока не встретим начало слова
    ("q_err_l", "λ"): ("λ", "L", "q_err_l"),
    ("q_err_l", "a"): ("λ", "L", "q_err_l_2"),
    ("q_err_l", "b"): ("λ", "L", "q_err_l_2"),

    # Стираем остатки слова и пишем 'b'
    ("q_err_l_2", "a"): ("λ", "L", "q_err_l_2"),
    ("q_err_l_2", "b"): ("λ", "L", "q_err_l_2"),
    ("q_err_l_2", "λ"): ("b", "N", "STOP"),

    # ВЕТКА УСПЕХА (слово ровно 'abb')
    ("q_succ_l", "a"): ("λ", "L", "q_succ_l"),
    ("q_succ_l", "b"): ("λ", "L", "q_succ_l"),
    ("q_succ_l", "λ"): ("a", "N", "STOP"),
}

CASES_OK = [
    ("abb", "a"),
    ("abba", "b"),
    ("aba", "b"),
    ("a", "b"),
    ("b", "b"),
    ("", "b"),
]