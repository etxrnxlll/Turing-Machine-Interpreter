"""Задача 14. Записать число n в двоичной системе.

Слово R — это n+1 единиц. Результат — двоичное представление n.
Пример: 111111 (6 единиц, n=5) => 101 (5 в двоичной).
Используем 'B' (разделитель) и 'E' (правый маркер).
"""

ALPHABET = {"1", "0", "B", "E"}

TRANSITIONS = {
    # q0: идем вправо, ставим маркер E в конце
    ("q0", "1"): ("1", "R", "q0"),
    ("q0", "λ"): ("E", "L", "q1"),

    # q1: стираем крайнюю правую 1 (вычитаем +1)
    ("q1", "1"): ("λ", "L", "q2"),

    # q2: идем влево до начала и ставим разделитель B
    ("q2", "1"): ("1", "L", "q2"),
    ("q2", "λ"): ("B", "R", "q3"),

    # q3: идем вправо от B, ищем оставшиеся единицы
    ("q3", "λ"): ("λ", "R", "q3"),
    ("q3", "1"): ("λ", "L", "q4"),
    ("q3", "E"): ("λ", "L", "q7"),       # Единицы кончились, идем очищать

    # q4: идем влево до B, чтобы прибавить 1 к двоичному числу
    ("q4", "1"): ("1", "L", "q4"),
    ("q4", "λ"): ("λ", "L", "q4"),
    ("q4", "B"): ("B", "L", "q5"),

    # q5: прибавляем 1 к двоичному числу (с переносом разряда)
    ("q5", "1"): ("0", "L", "q5"),
    ("q5", "0"): ("1", "R", "q6"),
    ("q5", "λ"): ("1", "R", "q6"),

    # q6: возвращаемся вправо к B
    ("q6", "0"): ("0", "R", "q6"),
    ("q6", "1"): ("1", "R", "q6"),
    ("q6", "B"): ("B", "R", "q3"),

    # q7: идем влево до B для финальной очистки
    ("q7", "λ"): ("λ", "L", "q7"),
    ("q7", "B"): ("B", "L", "q8"),

    # q8: проверяем, пустое ли двоичное число
    ("q8", "1"): ("1", "R", "q9"),
    ("q8", "0"): ("0", "R", "q9"),
    ("q8", "λ"): ("λ", "R", "q10"),

    # q9: двоичное число есть, удаляем B
    ("q9", "B"): ("λ", "N", "STOP"),

    # q10: двоичное число пустое (n=0), ставим 0 вместо B
    ("q10", "B"): ("0", "N", "STOP"),
}

CASES_OK = [
    ("111111", "101"),
    ("1", "0"),
    ("11", "1"),
    ("111", "10"),
    ("1111", "11"),
    ("11111", "100"),
]