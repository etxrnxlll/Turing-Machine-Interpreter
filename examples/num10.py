"""Задача 10. Приписать справа к слову столько единиц, сколько в нем 'b'.

Пример: ababb => ababb111.
Для подсчета используем временный символ 'x'.
"""

ALPHABET = {"a", "b", "1", "x"}

TRANSITIONS = {
    # q0: ищем первое непомеченное 'b'
    ("q0", "a"): ("a", "R", "q0"),
    ("q0", "1"): ("1", "R", "q0"),
    ("q0", "b"): ("x", "R", "q1"),   # Нашли 'b', временно меняем на 'x'
    ("q0", "λ"): ("λ", "N", "STOP"), # Все 'b' обработаны, останавливаемся

    # q1: идем в конец слова, чтобы добавить '1'
    ("q1", "a"): ("a", "R", "q1"),
    ("q1", "b"): ("b", "R", "q1"),
    ("q1", "1"): ("1", "R", "q1"),
    ("q1", "λ"): ("1", "L", "q2"),   # Дописали '1', идем обратно к 'x'

    # q2: идем обратно к нашему 'x', чтобы восстановить его в 'b'
    ("q2", "a"): ("a", "L", "q2"),
    ("q2", "b"): ("b", "L", "q2"),
    ("q2", "1"): ("1", "L", "q2"),
    ("q2", "x"): ("b", "R", "q0"),   # Нашли 'x', меняем на 'b' и ищем следующий
}

CASES_OK = [
    ("", ""),
    ("a", "a"),
    ("b", "b1"),
    ("bb", "bb11"),
    ("abab", "abab11"),
    ("ababb", "ababb111"),
]