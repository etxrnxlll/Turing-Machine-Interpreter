"""Задача 15. Проверить правильность расстановки скобок.

Максимальная вложенность скобок равна 3.
Если выражение правильное — приписать справа '(', иначе — ')'.
Алфавит: {(, )}.
Состояния q0-q3 хранят текущую глубину вложенности.
"""

ALPHABET = {"(", ")"}

TRANSITIONS = {
    # q0: глубина 0
    ("q0", "("): ("(", "R", "q1"),
    ("q0", ")"): (")", "R", "q_err"),  # Закрывающая скобка без открывающей
    ("q0", "λ"): ("(", "N", "STOP"),  # Конец слова на глубине 0 — успех!

    # q1: глубина 1
    ("q1", "("): ("(", "R", "q2"),
    ("q1", ")"): (")", "R", "q0"),
    ("q1", "λ"): (")", "N", "STOP"),  # Конец слова, но скобки не закрыты — ошибка

    # q2: глубина 2
    ("q2", "("): ("(", "R", "q3"),
    ("q2", ")"): (")", "R", "q1"),
    ("q2", "λ"): (")", "N", "STOP"),  # Ошибка

    # q3: глубина 3 (максимальная)
    ("q3", "("): ("(", "R", "q_err"),  # Попытка открыть 4-ю скобку — превышение вложенности
    ("q3", ")"): (")", "R", "q2"),
    ("q3", "λ"): (")", "N", "STOP"),  # Ошибка

    # q_err: состояние ошибки. Просто идем в конец и дописываем ')'
    ("q_err", "("): ("(", "R", "q_err"),
    ("q_err", ")"): (")", "R", "q_err"),
    ("q_err", "λ"): (")", "N", "STOP"),
}

CASES_OK = [
    ("", "("),
    ("()", "()("),
    ("(())", "(())("),
    ("((()))", "((()))("),
    ("()()", "()()("),
    ("()(())", "()(())("),

    (")(", ")()"),
    (")", "))"),
    ("(", "()"),
    ("(()", "(())"),
    ("(((())))", "(((()))))"),
]