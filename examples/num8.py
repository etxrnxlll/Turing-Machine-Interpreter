"""Задача 8. Проверить, начинается ли слово с 'abb'.

Если да — добавить в начало 'a', иначе — 'b'.
Алфавит: {a, b}.
"""

ALPHABET = {"a", "b"}

TRANSITIONS = {
    # q0, q1, q2: проверка первых трех символов
    ("q0", "a"): ("a", "R", "q1"),
    ("q0", "b"): ("b", "L", "q5"),       # Не начинается с 'a' — ошибка (идем влево)
    ("q0", "λ"): ("λ", "L", "q5"),       # Пустое слово — ошибка (идем влево)

    ("q1", "b"): ("b", "R", "q2"),
    ("q1", "a"): ("a", "L", "q5"),       # Второй символ не 'b'
    ("q1", "λ"): ("λ", "L", "q5"),       # Слишком короткое слово (идем влево)

    ("q2", "b"): ("b", "L", "q3"),       # Найдено 'abb'! Идем влево для записи 'a'
    ("q2", "a"): ("a", "L", "q5"),       # Третий символ не 'b'
    ("q2", "λ"): ("λ", "L", "q5"),       # Слишком короткое слово (идем влево)

    # q3: успех. Идем в начало и пишем 'a'
    ("q3", "a"): ("a", "L", "q3"),
    ("q3", "b"): ("b", "L", "q3"),
    ("q3", "λ"): ("a", "N", "STOP"),

    # q5: неудача. Идем в начало и пишем 'b'
    ("q5", "a"): ("a", "L", "q5"),
    ("q5", "b"): ("b", "L", "q5"),
    ("q5", "λ"): ("b", "N", "STOP"),
}

CASES_OK = [
    ("abb", "aabb"),
    ("abba", "aabba"),
    ("abbabb", "aabbabb"),
    ("aba", "baba"),
    ("aab", "baab"),
    ("baa", "bbaa"),
    ("b", "bb"),
    ("a", "ba"),
    ("", "b"),
]