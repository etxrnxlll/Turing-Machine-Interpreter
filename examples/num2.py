"""Задача 2. В слове заменить все b на чётных позициях на a.

Конвенция: позиции нумеруются с единицы, 1-я — первый символ.
Чётные позиции: 2-я, 4-я, 6-я, ... На них 'b' заменяется на 'a'.
Алфавит: {a, b}.
"""
# алфавит символов
ALPHABET = {"a", "b"}

# таблица переходов, λ - это пустой символ
TRANSITIONS = {
    # q0: нечётные позиции (1-я, 3-я, 5-я...) — ничего не меняем
    ("q0", "a"): ("a", "R", "q1"),
    ("q0", "b"): ("b", "R", "q1"),
    ("q0", "λ"): ("λ", "L", "STOP"),

    # q1: чётные позиции (2-я, 4-я, 6-я...) — заменяем 'b' на 'a'
    ("q1", "a"): ("a", "R", "q0"),
    ("q1", "b"): ("a", "R", "q0"),
    ("q1", "λ"): ("λ", "L", "STOP"),
}

CASES_OK = [
    ("", ""),
    ("a", "a"),
    ("b", "b"),
    ("aa", "aa"),
    ("ab", "aa"),
    ("ba", "ba"),
    ("bb", "ba"),
    ("aaa", "aaa"),
    ("aba", "aaa"),
    ("bbb", "bab"),
    ("abab", "aaaa"),
    ("bbbb", "baba"),
    ("aab", "aab"),
]