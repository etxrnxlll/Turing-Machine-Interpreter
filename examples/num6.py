"""Задача 6. Проверить, является ли слово последовательностью [a]n [b]m [a]k.

Где n, m, k — положительные числа (то есть n >= 1, m >= 1, k >= 1).
Запись [a]k означает последовательность состоящую из k символов a.
Слово должно состоять из трех групп: сначала 'a', потом 'b', потом снова 'a'.
Если да — добавить в конец 'a', иначе — 'b'.
"""

ALPHABET = {"a", "b"}

TRANSITIONS = {
    # q0: самое начало слова, ожидаем первую 'a'
    ("q0", "a"): ("a", "R", "q1"),
    ("q0", "b"): ("b", "R", "q4"),       # Нет первой группы 'a' — ошибка
    ("q0", "λ"): ("λ", "N", "q4"),       # Пустое слово — ошибка (N, чтобы не оставлять λ)

    # q1: читаем оставшиеся 'a' первой группы
    ("q1", "a"): ("a", "R", "q1"),
    ("q1", "b"): ("b", "R", "q2"),       # Началась группа 'b'
    ("q1", "λ"): ("λ", "N", "q4"),       # Слово кончилось, нет 'b' — ошибка

    # q2: читаем группу 'b'
    ("q2", "b"): ("b", "R", "q2"),
    ("q2", "a"): ("a", "R", "q3"),       # Началась вторая группа 'a'
    ("q2", "λ"): ("λ", "N", "q4"),       # Слово кончилось, нет второй 'a' — ошибка

    # q3: читаем вторую группу 'a'
    ("q3", "a"): ("a", "R", "q3"),
    ("q3", "b"): ("b", "R", "q4"),       # Снова встретили 'b' — ошибка (нарушен порядок)
    ("q3", "λ"): ("a", "N", "STOP"),     # Дошли до конца, все группы на месте — пишем 'a'

    # q4: состояние ошибки. Идем в конец (если стоим не на нем) и пишем 'b'
    ("q4", "a"): ("a", "R", "q4"),
    ("q4", "b"): ("b", "R", "q4"),
    ("q4", "λ"): ("b", "N", "STOP"),
}

CASES_OK = [
    ("aba", "abaa"),         # n=1, m=1, k=1
    ("aaba", "aabaa"),       # n=2, m=1, k=1
    ("abba", "abbaa"),       # n=1, m=2, k=1
    ("aabbaa", "aabbaaa"),   # n=2, m=2, k=2
    ("abab", "ababb"),       # Порядок нарушен (a-b-a-b)
    ("ba", "bab"),           # Нет первой группы 'a'
    ("ab", "abb"),           # Нет второй группы 'a'
    ("aa", "aab"),           # Нет группы 'b'
    ("", "b"),               # Пустое слово
]