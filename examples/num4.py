"""Задача 4. Проверить, все ли символы в слове одинаковы.

Если все символы одинаковы — добавить в конец 'a'.
Если есть разные символы — добавить в конец 'b'.
Алфавит: {a, b}.
"""

ALPHABET = {"a", "b"}

TRANSITIONS = {
    # Читаем первый символ
    ("q0", "a"): ("a", "R", "q1"),
    ("q0", "b"): ("b", "R", "q2"),
    ("q0", "λ"): ("a", "N", "STOP"), # Пустое слово считаем однородным

    # Состояние q1: проверяем, что все символы 'a'
    ("q1", "a"): ("a", "R", "q1"),
    ("q1", "b"): ("b", "R", "q3"),   # Нашли 'b' — символы разные, идем в q3
    ("q1", "λ"): ("a", "N", "STOP"), # Дошли до конца, все 'a' — пишем 'a'

    # Состояние q2: проверяем, что все символы 'b'
    ("q2", "b"): ("b", "R", "q2"),
    ("q2", "a"): ("a", "R", "q3"),   # Нашли 'a' — символы разные, идем в q3
    ("q2", "λ"): ("a", "N", "STOP"), # Дошли до конца, все 'b' — пишем 'a'

    # Состояние q3: символы разные, нужно дойти до конца и дописать 'b'
    ("q3", "a"): ("a", "R", "q3"),
    ("q3", "b"): ("b", "R", "q3"),
    ("q3", "λ"): ("b", "N", "STOP"), # Дописываем 'b'
}

